// Icon utility functions
export const getIcon = (iconName) => {
  const iconMap = {
    heart: Heart,
    play: Play,
    pause: Pause,
    menu: Menu,
    search: Search,
    user: User,
    home: Home,
  };
  return iconMap[iconName.toLowerCase()] || null;
};
export const hasIcon = (iconName) => {
  return getIcon(iconName) !== null;
};
